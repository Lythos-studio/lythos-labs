// Regenerates the files that list every block: src/catalog.ts, src/lab/fixtures.ts and src/styles/lab.css.
// Usage: node scripts/register.mjs   (run after adding a folder under src/blocks)
import { existsSync, readdirSync, writeFileSync } from "node:fs";

const HEADER = `/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at https://mozilla.org/MPL/2.0/. */
`;
const ORDER = [
  "button", "field", "choice", "tabs", "accordion", "dialog", "popover", "tooltip", "menu", "toast", "feedback", "card",
  "combobox", "command-palette", "data-table", "breadcrumb", "stepper", "date-picker", "slider", "toggle-group", "file-drop",
  "sortable-list", "split-pane", "tree-view", "form-kit", "inline-edit", "timeline",
];
const src = new URL("../src/", import.meta.url);
const present = readdirSync(new URL("blocks/", src), { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name);
const unknown = present.filter((s) => !ORDER.includes(s));
if (unknown.length) throw new Error(`Add to ORDER in scripts/register.mjs: ${unknown.join(", ")}`);
const slugs = ORDER.filter((s) => present.includes(s) && existsSync(new URL(`blocks/${s}/contract.ts`, src)));
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

writeFileSync(
  new URL("catalog.ts", src),
  `${HEADER}
import type { BlockEntry } from "./catalog-types";
${slugs.map((s) => `import { entry as ${camel(s)} } from "./blocks/${s}/contract";`).join("\n")}

/** Every block, as plain data (no React): used by the lab, the generators, the Node tests and the end-to-end tests. Generated by scripts/register.mjs. */
export const catalog: BlockEntry[] = [${slugs.map(camel).join(", ")}];

export const bySlug = (slug: string): BlockEntry | undefined => catalog.find((e) => e.meta.slug === slug);
`,
);
writeFileSync(
  new URL("lab/fixtures.ts", src),
  `${HEADER}
import type { FixtureModule } from "./types";

/** Fixtures are loaded on demand, so the overview does not pay for every block. Each import path is a literal so the bundler can split it. Generated by scripts/register.mjs. */
export const fixtures: Record<string, () => Promise<FixtureModule>> = {
${slugs.map((s) => `  "${s}": () => import("../blocks/${s}/fixture"),`).join("\n")}
};
`,
);
writeFileSync(
  new URL("styles/lab.css", src),
  `${HEADER}
/* Generated by scripts/register.mjs: the base, every block and the helpers for the live examples. */
@import "./base.css";
${slugs.map((s) => `@import "../blocks/${s}/${s}.css";`).join("\n")}
@import "./demo.css";
`,
);
console.log(`registered ${slugs.length} blocks: ${slugs.join(", ")}`);
