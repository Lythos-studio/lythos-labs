// Writes src/generated/{sources.ts,sizes.json,evidence.json}. Run `npm run e2e` first so the evidence reflects the current code.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { catalog } from "../src/catalog";
import { buildSizes, buildSources, listJson, sourceHash } from "./lib";

const HEADER = `/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at https://mozilla.org/MPL/2.0/. */
`;
const out = new URL("../src/generated/", import.meta.url);
mkdirSync(out, { recursive: true });

writeFileSync(new URL("sources.ts", out), `${HEADER}\n// Generated by scripts/gen.ts: the source of every block and the core files it uses, for the Code view and the starter kit.\nexport const sources: Record<string, string> = ${JSON.stringify(buildSources(), null, 1)};\n`);
const sizes = buildSizes();
writeFileSync(new URL("sizes.json", out), JSON.stringify(sizes, null, 1) + "\n");

const e2e = new URL("../e2e/out/", import.meta.url);
type Parity = { harness: Record<string, string>; real: Record<string, string>; at: string };
type Axe = { slug: string; theme: string; violations: string[]; passes?: number };
const files = listJson(e2e);
const evidence: Record<string, unknown> = {};
for (const { meta, contract } of catalog) {
  const runs = files.filter((f) => f.startsWith(`parity-${meta.slug}--`)).map((f) => JSON.parse(readFileSync(new URL(f, e2e), "utf8")) as { id: string; real: string; harness: string; at: string });
  const parity: Parity | null = runs.length
    ? { real: Object.fromEntries(runs.map((r) => [r.id, r.real])), harness: Object.fromEntries(runs.map((r) => [r.id, r.harness])), at: runs.map((r) => r.at).sort().at(-1)! }
    : null;
  const axeRuns: Axe[] = files.filter((f) => f.startsWith(`axe-${meta.slug}-`)).map((f) => JSON.parse(readFileSync(new URL(f, e2e), "utf8")));
  const total = contract.behaviours.length;
  const native = contract.behaviours.filter((b) => b.kind === "native").length;
  evidence[meta.slug] = {
    sourceHash: sourceHash(meta.slug),
    behaviours: total,
    native,
    realKeyboardPassed: parity ? Object.values(parity.real).filter((v) => v === "pass").length : 0,
    inPagePassed: parity ? Object.values(parity.harness).filter((v) => v === "pass").length : 0,
    axeStates: axeRuns.length,
    axeViolations: axeRuns.reduce((n, r) => n + r.violations.length, 0),
    verifiedAt: parity?.at ?? null,
  };
}
writeFileSync(new URL("evidence.json", out), JSON.stringify({ generatedBy: "scripts/gen.ts", note: "Measured by the end-to-end tests (real Chromium, real keyboard, axe-core). Not a certification.", blocks: evidence }, null, 1) + "\n");
console.log(`generated sources, sizes and evidence for ${catalog.length} blocks (e2e results found: ${existsSync(e2e) ? files.length : 0})`);
