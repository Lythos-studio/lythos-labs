import type { BlockEntry } from "./catalog-types";
import { entry as button } from "./blocks/button/contract";
import { entry as field } from "./blocks/field/contract";
import { entry as choice } from "./blocks/choice/contract";
import { entry as tabs } from "./blocks/tabs/contract";
import { entry as accordion } from "./blocks/accordion/contract";

/** Every block, as plain data (no React): used by the lab, the generators, the Node tests and the end-to-end tests. Generated by scripts/register.mjs. */
export const catalog: BlockEntry[] = [button, field, choice, tabs, accordion];

export const bySlug = (slug: string): BlockEntry | undefined => catalog.find((e) => e.meta.slug === slug);
